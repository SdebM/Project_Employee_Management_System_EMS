CREATE TABLE IF NOT EXISTS audit_log (
    id          SERIAL PRIMARY KEY,
    user_id     INT REFERENCES users(id),
    action_type VARCHAR(50) NOT NULL,
    timestamp   TIMESTAMP DEFAULT NOW(),
    details     TEXT
);

