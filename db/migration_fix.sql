-- 2. Автогенерация первичных ключей (IDENTITY) + синхронизация sequence
-- ----------------------------------------------------------------------------

-- employees.employee_id
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'employees'::regclass
          AND attname  = 'employee_id'
          AND attidentity IN ('a', 'd')
    ) THEN
        ALTER TABLE employees
            ALTER COLUMN employee_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
EXCEPTION WHEN others THEN
    RAISE NOTICE 'employees.employee_id: пропуск (%)', SQLERRM;
END $$;

DO $$
DECLARE
    seq_text TEXT;
BEGIN
    seq_text := pg_get_serial_sequence('employees', 'employee_id');
    IF seq_text IS NOT NULL THEN
        PERFORM setval(seq_text,
            COALESCE((SELECT MAX(employee_id) FROM employees), 0) + 1,
            false);
    END IF;
END $$;

