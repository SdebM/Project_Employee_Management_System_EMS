-- Устраняет проблемы, обнаруженные при запуске приложения:
--
--   1) «Невозможно добавить сотрудника» — в дампе db/empls_db.sql первичные
--      ключи employees.employee_id, departments.department_id,
--      projects.project_id объявлены как INTEGER PRIMARY KEY БЕЗ значения
--      по умолчанию. INSERT без явного ID падал:
--      «null value in column "employee_id" violates not-null constraint».
--      => Добавляем GENERATED BY DEFAULT AS IDENTITY (PG 10+) и сдвигаем
--         sequence за MAX(id), чтобы новые записи не конфликтовали с сидами.
--
--   2) «У менеджера не выводится список отделов» — сервис вызывает
--      get_by_id(), который читает колонку departments.description,
--      отсутствующую в дампе => UndefinedColumn => пустой список.
--      => Добавляем колонку departments.description.
--
--   3) Журнал действий: сервис пишет в audit_log при каждом создании/
--      изменении записей — таблица должна существовать.
--
-- Скрипт ИДЕМПОТЕНТНЫЙ: безопасно запускать повторно.
--
-- Запуск из консоли:   psql -d empls_db -f migration_fix.sql
-- Запуск в pgAdmin:    открыть Query Tool на базе empls_db, вставить файл,
--                      выполнить весь скрипт (Execute/Play, F5).
-- ============================================================================

